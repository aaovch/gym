export function completionPhrase(seed: string): string {
  let hash = 2166136261;
  for (let index = 0; index < seed.length; index += 1) {
    hash ^= seed.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return COMPLETION_PHRASES[(hash >>> 0) % COMPLETION_PHRASES.length];
}
